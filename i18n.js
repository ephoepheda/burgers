const i18n = {
    currentLang: 'en',
    
    init: () => {
        const savedLang = localStorage.getItem('queenBurgerLang') || 'en';
        i18n.setLanguage(savedLang);
    },

    setLanguage: (lang) => {
        i18n.currentLang = lang;
        localStorage.setItem('queenBurgerLang', lang);
        
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerText = translations[lang][key];
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang][key]) {
                el.placeholder = translations[lang][key];
            }
        });

        document.querySelectorAll('[data-i18n-label]').forEach(el => {
            const key = el.getAttribute('data-i18n-label');
            if (translations[lang][key]) {
                el.label = translations[lang][key];
            }
        });

        const currentLangDisplay = document.getElementById('currentLang');
        if (currentLangDisplay) {
            currentLangDisplay.innerText = lang.toUpperCase();
        }

        // Trigger custom event for app to re-render dynamic content (menu, etc)
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
    },

    t: (key) => {
        return translations[i18n.currentLang][key] || key;
    }
};

window.i18n = i18n;
document.addEventListener('DOMContentLoaded', i18n.init);
